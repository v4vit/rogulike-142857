_PALETTE = set(
    "K#D0L7W S$&89rAxXw4O%2YF!5GigjVh3Cck~TI1Bb uUP pQv@Mm;NnHJ6EeZ"
) | {'.'}


def check(name, art, width=16):
    errs = []
    for i, row in enumerate(art):
        if len(row) != width:
            errs.append(f"  行{i}: 长度{len(row)} != {width}: '{row}'")
    unknown = set()
    for row in art:
        unknown |= set(row) - _PALETTE
    if unknown:
        errs.append(f"  未知字符(不在色板): {sorted(unknown)}")
    if errs:
        print(f"[{name}] 有问题:")
        for e in errs:
            print(e)
        return False
    print(f"[{name}] OK ({len(art)}行x{width}列)")
    return True


